"""LAB ERP logo: a white lab flask on the brand blue. Writes every icon from one shape.

    python3 desktop/make_logo.py      (needs Pillow; run from any folder)

Outputs: desktop/icon.ico, frontend/public/favicon.svg, frontend/public/logo-192.png,
mobile/android/app/src/main/res/drawable/ic_launcher_fg.xml. The flask path is also in
frontend/src/components/BrandMark.tsx and both setup.html files (FLASK below).
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
BLUE = "#2563eb"
LIQUID = "#93c5fd"

# 32x32 design grid. M/L/Q commands only, so the same data drives SVG, Android vector and Pillow.
FLASK = [("M", 12.5, 5), ("L", 19.5, 5), ("Q", 20.5, 5, 20.5, 6), ("Q", 20.5, 7, 19.5, 7), ("L", 19, 7),
         ("L", 19, 12.4), ("L", 25.2, 22.6), ("Q", 26.6, 25.3, 23.6, 26.5), ("L", 8.4, 26.5),
         ("Q", 5.4, 25.3, 6.8, 22.6), ("L", 13, 12.4), ("L", 13, 7), ("L", 12.5, 7), ("Q", 11.5, 7, 11.5, 6),
         ("Q", 11.5, 5, 12.5, 5)]
LIQ = [("M", 10.6, 18.6), ("L", 21.4, 18.6), ("L", 23.6, 22.3), ("Q", 24.4, 24, 22.6, 24.4), ("L", 9.4, 24.4),
       ("Q", 7.6, 24, 8.4, 22.3)]
BUBBLES = [(14.6, 21.4, 1.0), (18.2, 22.4, 0.7)]


def d_attr(cmds, sx=1.0, ox=0.0, oy=0.0, nd=2) -> str:
    out = []
    for c, *v in cmds:
        pts = [round(ox + x * sx if i % 2 == 0 else oy + x * sx, nd) for i, x in enumerate(v)]
        out.append(c + " ".join(f"{p:g}" for p in pts))
    return "".join(out) + "Z"


def polygon(cmds, scale: float) -> list[tuple[float, float]]:
    pts: list[tuple[float, float]] = []
    cur = (0.0, 0.0)
    for c, *v in cmds:
        if c in "ML":
            cur = (v[0], v[1])
            pts.append(cur)
        else:  # quadratic Bezier, sampled
            (cx, cy, x, y), (x0, y0) = v, cur
            for i in range(1, 13):
                t = i / 12
                pts.append(((1 - t) ** 2 * x0 + 2 * (1 - t) * t * cx + t * t * x,
                            (1 - t) ** 2 * y0 + 2 * (1 - t) * t * cy + t * t * y))
            cur = (x, y)
    return [(x * scale, y * scale) for x, y in pts]


def bitmap(size: int) -> Image.Image:
    k = 8  # supersampling
    s = size * k / 32
    im = Image.new("RGBA", (size * k, size * k), (0, 0, 0, 0))
    g = ImageDraw.Draw(im)
    g.rounded_rectangle((0, 0, size * k - 1, size * k - 1), radius=7 * s, fill=BLUE)
    g.polygon(polygon(FLASK, s), fill="white")
    g.polygon(polygon(LIQ, s), fill=LIQUID)
    for x, y, r in BUBBLES:
        g.ellipse(((x - r) * s, (y - r) * s, (x + r) * s, (y + r) * s), fill="white")
    return im.resize((size, size), Image.LANCZOS)


def svg() -> str:
    bubbles = "".join(f'<circle cx="{x}" cy="{y}" r="{r}" fill="#fff"/>' for x, y, r in BUBBLES)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="7" '
            f'fill="{BLUE}"/><path d="{d_attr(FLASK)}" fill="#fff"/><path d="{d_attr(LIQ)}" fill="{LIQUID}"/>'
            f'{bubbles}</svg>\n')


def android_vector() -> str:
    # 108dp canvas, art kept inside the 66dp safe zone: 32 units -> 60dp, centred
    sx, o = 60 / 32, 24.0
    bub = "".join(
        f'\n    <path android:fillColor="#FFFFFF" android:pathData="M{o + (x - r) * sx:g},{o + y * sx:g}'
        f'a{r * sx:g},{r * sx:g} 0,1 1,{2 * r * sx:g},0a{r * sx:g},{r * sx:g} 0,1 1,{-2 * r * sx:g},0z" />'
        for x, y, r in BUBBLES)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- LAB ERP flask, generated by desktop/make_logo.py; inside the 66dp adaptive-icon safe zone. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#FFFFFF"
        android:pathData="{d_attr(FLASK, sx, o, o)}" />
    <path android:fillColor="{LIQUID.upper()}"
        android:pathData="{d_attr(LIQ, sx, o, o)}" />{bub}
</vector>
'''


def main() -> None:
    big = bitmap(256)
    big.save(ROOT / "desktop" / "icon.ico", sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128),
                                                   (256, 256)])
    bitmap(192).save(ROOT / "frontend" / "public" / "logo-192.png")
    (ROOT / "frontend" / "public" / "favicon.svg").write_text(svg(), encoding="utf-8")
    (ROOT / "mobile" / "android" / "app" / "src" / "main" / "res" / "drawable" / "ic_launcher_fg.xml").write_text(
        android_vector(), encoding="utf-8")
    print("flask path:", d_attr(FLASK))
    print("liquid path:", d_attr(LIQ))


if __name__ == "__main__":
    main()
